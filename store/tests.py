class CouponTests(TestCase):
    def setUp(self):
        now = timezone.now()
        self.coupon = Coupon.objects.create(
            code='SAVE10', name='Save 10', discount_type='percentage',
            discount_value=Decimal('10'), minimum_amount=Decimal('100'),
            valid_from=now - timedelta(days=1), valid_until=now + timedelta(days=1),
            is_active=True, usage_limit_per_user=1,
        )

    def test_valid_coupon(self):
        valid, _ = self.coupon.is_valid(None, Decimal('500'))
        self.assertTrue(valid)

    def test_below_minimum(self):
        valid, msg = self.coupon.is_valid(None, Decimal('50'))
        self.assertFalse(valid)

    def test_percentage_discount(self):
        self.assertEqual(self.coupon.calculate_discount(Decimal('1000')), Decimal('100'))

    def test_fixed_discount(self):
        self.coupon.discount_type = 'fixed'
        self.coupon.discount_value = Decimal('150')
        self.assertEqual(self.coupon.calculate_discount(Decimal('1000')), Decimal('150'))

    def test_fixed_discount_capped(self):
        self.coupon.discount_type = 'fixed'
        self.coupon.discount_value = Decimal('500')
        self.assertEqual(self.coupon.calculate_discount(Decimal('200')), Decimal('200'))


class CartManagerTests(TestCase):
    def setUp(self):
        self.product = make_product()
        self.client = Client()

    def test_add_to_cart_guest(self):
        response = self.client.post(reverse('add_to_cart', args=[self.product.id]), {'quantity': 2})
        self.assertEqual(response.status_code, 302)
        cart = Cart.objects.first()
        self.assertIsNotNone(cart)
        self.assertEqual(cart.items_count, 2)

    def test_add_same_product_accumulates(self):
        url = reverse('add_to_cart', args=[self.product.id])
        self.client.post(url, {'quantity': 1})
        self.client.post(url, {'quantity': 1})
        self.assertEqual(Cart.objects.first().items_count, 2)

    def test_cart_totals(self):
        self.client.post(reverse('add_to_cart', args=[self.product.id]), {'quantity': 3})
        cart = Cart.objects.first()
        self.assertEqual(cart.subtotal, Decimal('2400'))

    def test_update_quantity(self):
        self.client.post(reverse('add_to_cart', args=[self.product.id]), {'quantity': 1})
        item = CartItem.objects.first()
        self.client.post(reverse('update_cart', args=[item.id]), {'quantity': 5})
        item.refresh_from_db()
        self.assertEqual(item.quantity, 5)



def make_product(**kwargs):
    defaults = dict(
        name='Test Game', price=Decimal('1000'), discount_price=Decimal('800'),
        description='A test product', stock_quantity=10, is_active=True,
    )
    defaults.update(kwargs)
    return Product.objects.create(**defaults)


class ProductModelTests(TestCase):
    def test_current_price_uses_discount(self):
        p = make_product()
        self.assertEqual(p.current_price, Decimal('800'))

    def test_discount_percentage(self):
        p = make_product(price=Decimal('1000'), discount_price=Decimal('750'))
        self.assertEqual(p.discount_percentage, 25)

    def test_in_stock(self):
        p = make_product(stock_quantity=5)
        self.assertTrue(p.is_in_stock)
        p.stock_quantity = 0
        p.save()
        self.assertFalse(p.is_in_stock)

    def test_backorder_allows_stock(self):
        p = make_product(stock_quantity=0, allow_backorder=True)
        self.assertTrue(p.is_in_stock)

    def test_slug_autogenerated(self):
        p = make_product(name='Unique Product Name')
        self.assertEqual(p.slug, 'unique-product-name')

    def test_average_rating(self):
        p = make_product()
        u1 = User.objects.create_user('u1', password='x')
        u2 = User.objects.create_user('u2', password='x')
        u3 = User.objects.create_user('u3', password='x')
        Review.objects.create(product=p, user=u1, rating=5, comment='Great', is_approved=True)
        Review.objects.create(product=p, user=u2, rating=3, comment='Ok', is_approved=True)
        Review.objects.create(product=p, user=u3, rating=1, comment='Hidden', is_approved=False)
        self.assertEqual(p.average_rating, 4.0)
        self.assertEqual(p.review_count, 2)


